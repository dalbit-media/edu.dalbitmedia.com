export function getArticleReadingStats(item) {
  const details = ARTICLE_DETAILS[item.id];
  const text = [
    item.title, item.summary, ...item.keyPoints,
    ...details.sections.flatMap((section) => [section.heading, ...section.paragraphs]),
    item.application, ...item.discussionQuestions, item.limitation,
  ].join(' ').replace(/\s+/g, ' ').trim();
  return { characters: text.length, minutes: Math.round(text.length / 450) };
}
